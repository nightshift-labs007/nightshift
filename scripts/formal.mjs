// Formal-verification pipeline for the Lean models in formal/ (see formal/README.md).
//
//   node scripts/formal.mjs prove <Module|all>  submit Nightshift/<Module>.lean to Harmonic's Aristotle, accept proof-body changes only
//   node scripts/formal.mjs audit               build, then #print axioms for every published theorem (fails on sorryAx)
//   node scripts/formal.mjs vectors             emit Lean test vectors to test/vectors/vectors.json
//   node scripts/formal.mjs manifest            write public/verified/manifest.json + formal/PROPERTIES.md from the audit
//   node scripts/formal.mjs anchor              write the manifest hash to Algorand (needs ALGORAND_MNEMONIC)
//
// Secrets (ARISTOTLE_API_KEY, ALGORAND_MNEMONIC) come from the environment only and are never printed.
import { execFileSync, spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const FORMAL = path.join(ROOT, "formal");
const PROPS = JSON.parse(fs.readFileSync(path.join(FORMAL, "properties.json"), "utf8"));
const MANIFEST = path.join(ROOT, "public", "verified", "manifest.json");
const AUDIT_OUT = path.join(FORMAL, "audit.txt");
const ALLOWED_AXIOMS = new Set(["propext", "Classical.choice", "Quot.sound"]);
const MODULES = ["Guardian", "Vault", "Oracle", "Cloak"];

const env = { ...process.env, PYTHONUTF8: "1", PYTHONIOENCODING: "utf-8", PATH: `${path.join(os.homedir(), ".elan", "bin")}${path.delimiter}${process.env.PATH}` };
const run = (cmd, args, opts = {}) => {
  const r = spawnSync(cmd, args, { cwd: FORMAL, env, encoding: "utf8", maxBuffer: 64 << 20, shell: process.platform === "win32", ...opts });
  return { code: r.status ?? 1, out: `${r.stdout ?? ""}${r.stderr ?? ""}` };
};

// ---------------------------------------------------------------- audit

function writeAuditFile() {
  const lines = ["-- Generated by scripts/formal.mjs from formal/properties.json. Do not edit.", "import Nightshift", ""];
  for (const p of PROPS) lines.push(`#print axioms ${p.theorem}`);
  fs.writeFileSync(path.join(FORMAL, "Nightshift", "Audit.lean"), lines.join("\n") + "\n");
}

/** theorem name -> axioms it depends on, parsed from `#print axioms` output. */
function parseAudit(text) {
  const res = new Map();
  const flat = text.replace(/\r/g, "").replace(/\n\s+/g, " ");
  for (const m of flat.matchAll(/'([^']+)' depends on axioms: \[([^\]]*)\]/g)) res.set(m[1], m[2].split(",").map((s) => s.trim()).filter(Boolean));
  for (const m of flat.matchAll(/'([^']+)' does not depend on any axioms/g)) res.set(m[1], []);
  return res;
}

/** One self-contained file: Mathlib imported once, every module's source, then `#print axioms` for every
 *  published theorem. `lake env lean` re-elaborates and kernel-checks every proof in it. This avoids
 *  `lake build`, whose ProofWidgets JS step can't be satisfied from the prebuilt release on Windows. */
function writeDirectAuditFile() {
  const body = ["-- Generated by scripts/formal.mjs. Do not edit.", "import Mathlib", ""];
  for (const mod of MODULES) {
    const src = fs.readFileSync(path.join(FORMAL, "Nightshift", `${mod}.lean`), "utf8").replace(/\r/g, "");
    body.push(`-- ===== Nightshift/${mod}.lean =====`, src.replace(/^import .*$/gm, ""), "");
  }
  for (const p of PROPS) body.push(`#print axioms ${p.theorem}`);
  const file = path.join(FORMAL, ".audit", "All.lean");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body.join("\n") + "\n");
  return path.relative(FORMAL, file);
}

function audit() {
  writeAuditFile();
  let a;
  const build = process.platform === "win32" || process.argv.includes("--direct") ? null : run("lake", ["build"]);
  if (build && build.code === 0) {
    a = run("lake", ["env", "lean", "Nightshift/Audit.lean"]);
  } else {
    if (build) console.error("lake build failed; falling back to a direct kernel check");
    a = run("lake", ["env", "lean", writeDirectAuditFile()]);
  }
  if (/error:/.test(a.out)) {
    console.error(a.out.split("\n").filter((l) => /error/.test(l)).slice(0, 30).join("\n"));
    console.error("Lean reported errors: nothing counts as verified");
    fs.writeFileSync(AUDIT_OUT, "");
    process.exit(1);
  }
  fs.writeFileSync(AUDIT_OUT, a.out);
  const axioms = parseAudit(a.out);
  let unproven = 0;
  for (const p of PROPS) {
    const ax = axioms.get(p.theorem);
    const status = !ax ? "missing" : ax.includes("sorryAx") ? "pending" : ax.every((x) => ALLOWED_AXIOMS.has(x)) ? "verified" : "rejected";
    if (status !== "verified") unproven++;
    console.log(`${status.padEnd(9)} ${p.id.padEnd(4)} ${p.theorem}${ax && status !== "verified" ? `  [${ax.join(", ")}]` : ""}`);
  }
  console.log(`\n${PROPS.length - unproven}/${PROPS.length} properties verified`);
  return unproven;
}

// ---------------------------------------------------------------- vectors

function vectors() {
  // run through the Lean interpreter: a compiled executable would make Lake compile all of Mathlib to C
  const r = run("lake", ["env", "lean", "--run", "Vectors.lean"]);
  if (r.code !== 0) {
    console.error(r.out);
    process.exit(1);
  }
  const json = r.out.slice(r.out.indexOf("{"));
  JSON.parse(json); // must be valid
  fs.mkdirSync(path.join(ROOT, "test", "vectors"), { recursive: true });
  fs.writeFileSync(path.join(ROOT, "test", "vectors", "vectors.json"), json.trim() + "\n");
  console.log("wrote test/vectors/vectors.json");
}

// ---------------------------------------------------------------- manifest

const sha256 = (s) => crypto.createHash("sha256").update(s).digest("hex");

function sourceFingerprint() {
  const files = ["lakefile.toml", "lean-toolchain", "properties.json", "Vectors.lean", ...MODULES.map((m) => `Nightshift/${m}.lean`)];
  return sha256(files.map((f) => fs.readFileSync(path.join(FORMAL, f), "utf8")).join("\n\u0000\n"));
}

function gitCommit() {
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null; // the project is not a git repository yet
  }
}

/** The hash anchored on Algorand covers everything except the `algorand` block itself. */
const canonical = (m) => JSON.stringify({ ...m, algorand: undefined }, null, 2);

function manifest() {
  const axioms = fs.existsSync(AUDIT_OUT) ? parseAudit(fs.readFileSync(AUDIT_OUT, "utf8")) : new Map();
  const lakeManifest = JSON.parse(fs.readFileSync(path.join(FORMAL, "lake-manifest.json"), "utf8"));
  const mathlib = lakeManifest.packages.find((p) => p.name === "mathlib");
  const previous = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, "utf8")) : null;
  const m = {
    version: 1,
    generatedAt: new Date().toISOString(),
    gitCommit: gitCommit(),
    sourceSha256: sourceFingerprint(),
    lean: { toolchain: fs.readFileSync(path.join(FORMAL, "lean-toolchain"), "utf8").trim(), mathlib: mathlib?.rev ?? null },
    prover: "Harmonic Aristotle (proofs re-checked by the Lean kernel)",
    properties: PROPS.map((p) => {
      const ax = axioms.get(p.theorem);
      const status = ax && !ax.includes("sorryAx") && ax.every((x) => ALLOWED_AXIOMS.has(x)) ? "verified" : "pending";
      return { ...p, status, source: p.file.replace(/^formal\//, "/verified/src/") };
    }),
  };
  const hash = sha256(canonical(m));
  const keepTx = previous?.algorand?.manifestSha256 === hash ? previous.algorand.txId : null;
  m.algorand = { network: "testnet", manifestSha256: hash, txId: keepTx };
  fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
  fs.writeFileSync(MANIFEST, JSON.stringify(m, null, 2) + "\n");

  const md = [
    "# Properties",
    "",
    "Generated by `node scripts/formal.mjs manifest` from `properties.json` and the axiom audit. Do not edit.",
    "",
    "| ID | Module | Property | Theorem | Status | Assumptions |",
    "|---|---|---|---|---|---|",
    ...m.properties.map((p) => `| ${p.id} | ${p.module} | ${p.plain} | \`${p.theorem}\` | ${p.status} | ${p.assumptions} |`),
    "",
  ];
  fs.writeFileSync(path.join(FORMAL, "PROPERTIES.md"), md.join("\n"));
  // publish the sources next to the manifest so every property links to the Lean file it is proven in
  const pubSrc = path.join(ROOT, "public", "verified", "src");
  fs.mkdirSync(path.join(pubSrc, "Nightshift"), { recursive: true });
  for (const mod of MODULES) fs.copyFileSync(path.join(FORMAL, "Nightshift", `${mod}.lean`), path.join(pubSrc, "Nightshift", `${mod}.lean`));
  for (const doc of ["MAPPING.md", "PROPERTIES.md"]) fs.copyFileSync(path.join(FORMAL, doc), path.join(pubSrc, doc));
  const v = m.properties.filter((p) => p.status === "verified").length;
  console.log(`manifest: ${v}/${m.properties.length} verified, sha256 ${hash}`);
}

// ---------------------------------------------------------------- Aristotle

/** Everything except proof bodies: definitions and theorem statements must come back unchanged. */
function skeleton(src) {
  const out = [];
  let inProof = false;
  for (const raw of src.replace(/\r/g, "").split("\n")) {
    const line = raw.replace(/\s+$/, "");
    const topLevel = /^(theorem|lemma|def|noncomputable|abbrev|instance|structure|section|end|namespace|open|variable|include|import|--|\/-|@\[)/.test(line);
    if (topLevel) inProof = false;
    if (inProof) continue;
    if (line.trim() === "") continue;
    const by = line.indexOf(":= by");
    if (by >= 0) {
      out.push(line.slice(0, by + 5));
      inProof = true;
    } else out.push(line);
  }
  return out.join("\n");
}

async function prove(target) {
  if (!process.env.ARISTOTLE_API_KEY) {
    console.error("ARISTOTLE_API_KEY is not set. Add it to .env.local (never commit it) and run with: node --env-file=.env.local scripts/formal.mjs prove <Module>");
    process.exit(1);
  }
  const modules = target === "all" ? MODULES : [target];
  for (const mod of modules) {
    const rel = `Nightshift/${mod}.lean`;
    const file = path.join(FORMAL, rel);
    const before = fs.readFileSync(file, "utf8");
    if (!before.includes("sorry")) {
      console.log(`${rel}: no sorry left, skipping`);
      continue;
    }
    const work = fs.mkdtempSync(path.join(os.tmpdir(), "aristotle-"));
    const archive = path.join(work, "result.tar.gz");
    const prompt = `Fill in all sorries in ${rel}. Do not change any theorem statement, definition, import or hypothesis. If a statement is false, say so and give a counterexample instead of changing it.`;
    console.log(`submitting ${rel} to Aristotle (this can take a while)...`);
    const r = spawnSync("aristotle", ["submit", prompt, "--project-dir", ".", "--wait", "--destination", archive], {
      cwd: FORMAL,
      env,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      shell: false, // the prompt contains spaces; a shell would split it
      maxBuffer: 64 << 20,
    });
    const log = `${r.stdout ?? ""}${r.stderr ?? ""}`;
    fs.writeFileSync(path.join(FORMAL, `aristotle-${mod}.log`), log);
    if (r.status !== 0 || !fs.existsSync(archive)) {
      console.error(`Aristotle run failed for ${rel}; see formal/aristotle-${mod}.log`);
      continue;
    }
    applyArchive(mod, archive, work);
  }
}

/** Unpack an Aristotle result and accept it only if every definition and statement is unchanged. */
function applyArchive(mod, archive, work) {
  const rel = `Nightshift/${mod}.lean`;
  const file = path.join(FORMAL, rel);
  const before = fs.readFileSync(file, "utf8");
  // Windows: use the system bsdtar (Git Bash's GNU tar reads "C:" as a remote host)
  const tar = process.platform === "win32" ? path.join(process.env.SystemRoot ?? "C:\Windows", "System32", "tar.exe") : "tar";
  execFileSync(tar, ["-xzf", archive, "-C", work]);
  const found = findFile(work, `${mod}.lean`, "Nightshift");
  if (!found) {
    console.error(`${rel} not found in Aristotle's result; archive kept at ${archive}`);
    return false;
  }
  const after = fs.readFileSync(found, "utf8");
  if (skeleton(after) !== skeleton(before)) {
    fs.writeFileSync(path.join(FORMAL, `aristotle-${mod}.rejected.lean`), after);
    console.error(`REJECTED: Aristotle changed a definition or statement in ${rel}. Saved its version as formal/aristotle-${mod}.rejected.lean for review; working tree unchanged.`);
    return false;
  }
  fs.writeFileSync(file, after);
  const left = (after.match(/\bsorry\b/g) ?? []).length;
  console.log(`${rel}: accepted proof bodies (${left} sorry left). Re-check with: node scripts/formal.mjs audit`);
  return true;
}

/** Download a finished Aristotle project by id (e.g. after the CLI lost its connection) and apply it. */
function fetchResult(projectId, mod) {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "aristotle-"));
  const archive = path.join(work, "result.tar.gz");
  const r = spawnSync("aristotle", ["download", projectId, "--destination", archive], { cwd: FORMAL, env, encoding: "utf8", shell: false });
  if (r.status !== 0 || !fs.existsSync(archive)) {
    console.error(`download failed: ${(r.stderr ?? "").slice(-400)}`);
    process.exit(1);
  }
  applyArchive(mod, archive, work);
}

function findFile(dir, name, parent) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === ".lake") continue;
      const f = findFile(p, name, parent);
      if (f) return f;
    } else if (e.name === name && path.basename(dir) === parent) return p;
  }
  return null;
}

// ---------------------------------------------------------------- Algorand anchor

async function anchor() {
  const mnemonic = process.env.ALGORAND_MNEMONIC;
  if (!mnemonic) {
    console.error("ALGORAND_MNEMONIC is not set (run with --env-file=.env.local).");
    process.exit(1);
  }
  const m = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const hash = sha256(canonical(m));
  if (hash !== m.algorand.manifestSha256) {
    console.error("manifest changed since it was generated; run `node scripts/formal.mjs manifest` first");
    process.exit(1);
  }
  const algosdk = (await import("algosdk")).default;
  const account = algosdk.mnemonicToSecretKey(mnemonic.trim());
  const algod = new algosdk.Algodv2("", "https://testnet-api.algonode.cloud", "");
  const note = `nightshift:verified:v1:${hash}:${m.gitCommit ?? `src-${m.sourceSha256}`}`;
  const params = await algod.getTransactionParams().do();
  const txn = algosdk.makePaymentTxnWithSuggestedParamsFromObject({
    sender: account.addr,
    receiver: account.addr,
    amount: 0,
    note: new TextEncoder().encode(note),
    suggestedParams: params,
  });
  const signed = txn.signTxn(account.sk);
  const { txid } = await algod.sendRawTransaction(signed).do();
  await algosdk.waitForConfirmation(algod, txid, 8);
  m.algorand.txId = txid;
  fs.writeFileSync(MANIFEST, JSON.stringify(m, null, 2) + "\n");
  console.log(`anchored: https://lora.algokit.io/testnet/transaction/${txid}`);
}

// ---------------------------------------------------------------- main

const [cmd, arg] = process.argv.slice(2);
if (cmd === "audit") process.exit(audit() > 0 && process.argv.includes("--strict") ? 1 : 0);
else if (cmd === "vectors") vectors();
else if (cmd === "manifest") manifest();
else if (cmd === "prove") await prove(arg ?? "Guardian");
else if (cmd === "anchor") await anchor();
else if (cmd === "fetch") fetchResult(arg, process.argv[4] ?? "Guardian");
else {
  console.log("usage: node scripts/formal.mjs <prove [Module|all] | fetch <projectId> <Module> | audit [--strict] | vectors | manifest | anchor>");
  process.exit(1);
}
