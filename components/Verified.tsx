import manifest from "../public/verified/manifest.json";

// Rendered from the committed verification manifest at build time (no live API), per the formal spec.
// A property shows as verified only when the axiom audit found its proof complete (no sorry).

type Property = {
  id: string;
  module: string;
  plain: string;
  theorem: string;
  file: string;
  source: string;
  status: "verified" | "pending";
  assumptions: string;
};
type Manifest = {
  generatedAt: string;
  gitCommit: string | null;
  lean: { toolchain: string; mathlib: string | null };
  properties: Property[];
  algorand: { network: string; manifestSha256: string; txId: string | null };
};

const M = manifest as Manifest;
const MODULE_ORDER = ["Vault", "Guardian", "Oracle", "Cloak"];

/** Verified-property count per module, for the badges on the product cards. */
export function verifiedCount(module: string): number {
  return M.properties.filter((p) => p.module === module && p.status === "verified").length;
}

export function Verified() {
  const verified = M.properties.filter((p) => p.status === "verified").length;
  const total = M.properties.length;
  return (
    <div className="verified">
      <div className="verified-summary">
        <div className="card stat">
          <span className="unit">Properties proven</span>
          <div className={`v ${verified ? "accent" : ""}`}>
            {verified} / {total}
          </div>
        </div>
        <div className="card stat">
          <span className="unit">Proof checker</span>
          <div className="v verified-small">Lean 4 kernel</div>
          <p className="verified-meta mono">{M.lean.toolchain.replace("leanprover/lean4:", "Lean ")} · Mathlib {M.lean.mathlib ?? "—"}</p>
        </div>
        <div className="card stat">
          <span className="unit">Fingerprint</span>
          <div className="v verified-small mono">{M.algorand.manifestSha256.slice(0, 12)}…</div>
          <p className="verified-meta mono">
            {M.algorand.txId ? (
              <a href={`https://lora.algokit.io/${M.algorand.network}/transaction/${M.algorand.txId}`} target="_blank" rel="noopener noreferrer">
                Anchored on Algorand ↗
              </a>
            ) : (
              "Not yet anchored on Algorand"
            )}
          </p>
        </div>
      </div>

      {MODULE_ORDER.map((mod) => {
        const props = M.properties.filter((p) => p.module === mod);
        return (
          <div key={mod} className="verified-group">
            <h3>
              {mod} <span className="unit">{props.filter((p) => p.status === "verified").length} of {props.length} proven</span>
            </h3>
            <div className="verified-grid">
              {props.map((p) => (
                <article key={p.id} className={`card verified-card ${p.status}`}>
                  <div className="verified-top">
                    <span className="mono verified-id">{p.id}</span>
                    <span className={`pill-status ${p.status === "verified" ? "ok" : "pending"}`}>{p.status === "verified" ? "Verified" : "Proof pending"}</span>
                  </div>
                  <p className="verified-plain">{p.plain}</p>
                  <p className="verified-assume">{p.assumptions}</p>
                  <a className="verified-src mono" href={p.source} target="_blank" rel="noopener noreferrer">
                    {p.theorem.split(".").pop()} · {p.file.replace("formal/", "")} ↗
                  </a>
                </article>
              ))}
            </div>
          </div>
        );
      })}

      <div className="verified-honesty">
        <b>What this does and doesn&apos;t cover.</b> These proofs cover the mathematical models of Nightshift&apos;s logic, which are tested
        against the live code. They do not replace a smart contract security audit. The code-to-model mapping and every known gap are
        published in <a href="/verified/src/MAPPING.md">MAPPING.md</a>.
      </div>
      <p className="verified-foot mono">
        {verified > 0 ? "Verified using Harmonic's Aristotle." : "Proofs are generated by Harmonic's Aristotle and are pending."} Manifest generated{" "}
        {new Date(M.generatedAt).toISOString().slice(0, 10)}
        {M.gitCommit ? ` · commit ${M.gitCommit.slice(0, 7)}` : ""} · <a href="/verified/manifest.json">manifest.json</a>
      </p>
    </div>
  );
}
